"""
Pydantic models for Dataset database rows and creation payloads.

These schemas define the contract between the repository layer and the
service/router layers.  They are NOT SQLAlchemy ORM models.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class DatasetStatus(str, Enum):
    """Mirror of the Prisma DatasetStatus enum."""

    UPLOADED = "UPLOADED"
    PROCESSING = "PROCESSING"
    READY = "READY"
    ERROR = "ERROR"


class DatasetCreate(BaseModel):
    """Input schema for creating a new dataset row.

    ID and timestamps are generated by the repository.
    """

    name: str
    file_name: str = Field(alias="fileName")
    file_type: str = Field(alias="fileType")
    file_size_bytes: int = Field(alias="fileSizeBytes")
    file_url: str = Field(alias="fileUrl")
    project_id: str = Field(alias="projectId")

    model_config = {"populate_by_name": True}


class DatasetRow(BaseModel):
    """Output schema representing a dataset row returned from the database."""

    id: str
    name: str
    file_name: str = Field(alias="fileName")
    file_type: str = Field(alias="fileType")
    file_size_bytes: int = Field(alias="fileSizeBytes")
    file_url: str = Field(alias="fileUrl")
    parquet_url: str | None = Field(default=None, alias="parquetUrl")
    columns: Any | None = None
    row_count: int | None = Field(default=None, alias="rowCount")
    col_count: int | None = Field(default=None, alias="colCount")
    checksum: str | None = None
    status: DatasetStatus
    project_id: str = Field(alias="projectId")
    created_at: datetime = Field(alias="createdAt")
    updated_at: datetime = Field(alias="updatedAt")
    deleted_at: datetime | None = Field(default=None, alias="deletedAt")

    model_config = {"populate_by_name": True, "from_attributes": True}
